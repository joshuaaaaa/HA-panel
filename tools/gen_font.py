def enc(rows):
    w = len(rows[0])
    assert all(len(r) == w for r in rows), rows
    out = []
    for r in rows:
        v = 0
        for i, ch in enumerate(r):
            if ch == '1':
                v |= 0x80 >> i
        out.append("0x%02X" % v)
    return w, out

